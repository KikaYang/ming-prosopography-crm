"""
Generate the table of docs/modelling/identifiers_glossary_en.md from the models
(docs/modelling/*.ttl) and two files kept outside the models:
    docs/modelling/name_glosses_en.csv     English renderings of name nodes (D9: name nodes are @zh-Hant only)
    docs/modelling/glossary_basis_en.csv   basis of the English labels and explanations of type nodes
The table (identifier | Chinese | English | What it means | Gregorian date | basis) replaces everything
between the BEGIN/END markers; the hand-written text around it is left untouched.

    python scripts/naming_table.py           # rewrite the table
    python scripts/naming_table.py --check   # exit 1 if the table is out of date

Listed: every identifier in the project namespaces (/id/ and /vocab/) that carries a label, every
name node and every time-span (ts:) node.
- Chinese: @zh labels, and labels without a language tag (name:date-cbdb-421880, a CBDB field value).
- English: the @en label; for name nodes the rendering in name_glosses_en.csv; for a ts node the
  rendering of the date expression that identifies it.
- What it means: rdfs:comment @en of type nodes and of mpv: properties; for a ts node, the nodes it dates.
- Gregorian date: P82a/P82b of ts nodes; for date name nodes, the date in name_glosses_en.csv.
"""
import argparse
import csv
import datetime
import glob
import sys
from pathlib import Path

from rdflib import RDFS, Graph, Namespace, URIRef

ROOT = Path(__file__).resolve().parents[1]
MODELLING = ROOT / "docs" / "modelling"
DOC = MODELLING / "identifiers_glossary_en.md"
GLOSSES = MODELLING / "name_glosses_en.csv"
BASIS = MODELLING / "glossary_basis_en.csv"
BASE = "https://kikayang.github.io/ming-prosopography-crm/"
CRM = Namespace("http://www.cidoc-crm.org/cidoc-crm/")
BEGIN, END = "<!-- BEGIN TABLE (generated by scripts/naming_table.py) -->", "<!-- END TABLE -->"
ORDER = ["person", "group", "place", "doc", "work", "event", "pc", "ts", "name", "type", "mpv"]


def short(uri):
    rest = str(uri)[len(BASE):]
    if rest.startswith("id/"):
        prefix, local = rest[3:].split("/", 1)
    else:
        prefix, local = "mpv", rest.split("/", 1)[1]
    return f"{prefix}:{local}"


def cell(text):
    return (text or "—").replace("|", "\\|").replace("\n", " ")


def day(value):
    d = datetime.date.fromisoformat(str(value)[:10])
    return f"{d.day} {d.strftime('%B')} {d.year}"


def span(g, ts):
    a, b = g.value(ts, CRM["P82a_begin_of_the_begin"]), g.value(ts, CRM["P82b_end_of_the_end"])
    if a is None or b is None:
        return ""
    return day(a) if str(a)[:10] == str(b)[:10] else f"{day(a)} – {day(b)}"


def read_csv(path):
    with open(path, encoding="utf-8", newline="") as f:
        return {r["identifier"]: r for r in csv.DictReader(f)}


def table():
    g = Graph()
    for f in sorted(glob.glob(str(MODELLING / "*.ttl"))):
        g.parse(f)
    glosses, basis = read_csv(GLOSSES), read_csv(BASIS)
    nodes = {s for s in g.subjects() if isinstance(s, URIRef) and str(s).startswith(BASE)
             and (any(True for _ in g.objects(s, RDFS.label)) or "/id/ts/" in str(s) or "/id/name/" in str(s))}
    names = {short(s) for s in nodes if "/id/name/" in str(s)}
    missing = sorted(names - set(glosses))
    if missing:
        raise SystemExit(f"name_glosses_en.csv lacks: {', '.join(missing)}")
    rows = []
    for s in nodes:
        i = short(s)
        prefix = i.split(":", 1)[0]
        labels = list(g.objects(s, RDFS.label))
        zh = " / ".join(sorted({str(l) for l in labels if not l.language or l.language.startswith("zh")}))
        en = " / ".join(sorted({str(l) for l in labels if l.language == "en"}))
        means = greg = src = ""
        if prefix == "name":
            en, greg, src = glosses[i]["english"], glosses[i]["gregorian_date"], glosses[i]["basis"]
        elif prefix == "ts":
            nm = g.value(s, CRM["P1_is_identified_by"])
            if nm is not None:
                zh = " / ".join(str(l) for l in g.objects(nm, RDFS.label))
                en = glosses[short(nm)]["english"]
            dated = sorted(short(x) for x, _ in g.subject_predicates(s) if str(x).startswith(BASE) and x != nm)
            means = "time-span of " + ", ".join(f"`{d}`" for d in dated) if dated else ""
            greg, src = span(g, s), "P82a/P82b (D14)"
        elif prefix in ("type", "mpv"):
            means = " ".join(str(c) for c in g.objects(s, RDFS.comment) if c.language == "en")
            b = basis.get(i)
            if b:
                parts = []
                if b["label_basis"]:
                    parts.append(f"label: {b['label_basis']}")
                if b["explanation_basis"]:
                    parts.append(f"explanation: {b['explanation_basis']}")
                src = "; ".join(parts)
        key = (ORDER.index(prefix) if prefix in ORDER else len(ORDER), i)
        rows.append((key, f"`{i}`", zh, en, means, greg, src))
    rows.sort()
    lines = [BEGIN, "", "| identifier | Chinese | English | What it means | Gregorian date | basis |",
             "|---|---|---|---|---|---|"]
    lines += ["| " + " | ".join([r[1]] + [cell(c) for c in r[2:]]) + " |" for r in rows]
    lines += ["", END]
    return "\n".join(lines)


def render(text):
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + table() + tail


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    old = DOC.read_text(encoding="utf-8")
    new = render(old)
    if a.check:
        if new != old:
            print("docs/modelling/identifiers_glossary_en.md: table is out of date; run scripts/naming_table.py")
            return 1
        return 0
    DOC.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
