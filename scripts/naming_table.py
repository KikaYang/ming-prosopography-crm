"""
Generate the identifier table of docs/modelling/naming_en.md from the rdfs:label values in
docs/modelling/*.ttl. The table (identifier | Chinese | English) replaces everything between the
BEGIN/END markers in that file; the hand-written rules above it are left untouched.

    python scripts/naming_table.py           # rewrite the table
    python scripts/naming_table.py --check   # exit 1 if the table is out of date

Only identifiers in the project namespaces (/id/ and /vocab/) that carry at least one label are listed.
"""
import argparse
import glob
import sys
from pathlib import Path

from rdflib import Graph, RDFS, URIRef

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "modelling" / "naming_en.md"
BASE = "https://kikayang.github.io/ming-prosopography-crm/"
BEGIN, END = "<!-- BEGIN TABLE (generated by scripts/naming_table.py) -->", "<!-- END TABLE -->"
ORDER = ["person", "group", "place", "doc", "work", "event", "pc", "ts", "name", "type", "vocab"]


def short(uri):
    rest = str(uri)[len(BASE):]
    if rest.startswith("id/"):
        prefix, local = rest[3:].split("/", 1)
    else:
        prefix, local = "mpv", rest.split("/", 1)[1]
    return prefix, local


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def table():
    g = Graph()
    for f in sorted(glob.glob(str(ROOT / "docs" / "modelling" / "*.ttl"))):
        g.parse(f)
    rows = []
    for s in set(g.subjects(RDFS.label, None)):
        if not (isinstance(s, URIRef) and str(s).startswith(BASE)):
            continue
        labels = list(g.objects(s, RDFS.label))
        zh = sorted({str(l) for l in labels if (l.language or "").startswith("zh")})
        en = sorted({str(l) for l in labels if l.language == "en"})
        prefix, local = short(s)
        key = (ORDER.index(prefix) if prefix in ORDER else len(ORDER), prefix, local)
        rows.append((key, f"`{prefix}:{local}`", " / ".join(zh) or "—", " / ".join(en) or "—"))
    rows.sort()
    lines = [BEGIN, "", "| identifier | Chinese | English |", "|---|---|---|"]
    lines += [f"| {i} | {cell(zh)} | {cell(en)} |" for _, i, zh, en in rows]
    lines += ["", END]
    return "\n".join(lines)


def render(text):
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + table() + tail


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    old = DOC.read_text(encoding="utf-8")
    new = render(old)
    if a.check:
        if new != old:
            print("docs/modelling/naming_en.md: table is out of date; run scripts/naming_table.py")
            return 1
        return 0
    DOC.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
